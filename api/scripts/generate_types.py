"""Generate web/lib/kounos-types.ts from app.schemas (A03).

The web app must import the generated file, never a hand-written copy.
Run: ``python scripts/generate_types.py`` from ``api/``.
``tests/test_generate_types.py`` fails if the checked-in file drifts.
"""

import sys
import types
import typing
from datetime import date, datetime
from decimal import Decimal
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from pydantic import BaseModel

from app import schemas
from app.config import REPO_ROOT

OUT_PATH = REPO_ROOT / "web" / "lib" / "kounos-types.ts"

HEADER = """/**
 * Generated by api/scripts/generate_types.py from app.schemas. Do not edit.
 *
 * Money is a string (Python Decimal serializes as JSON string).
 * Dates and datetimes are ISO-8601 strings.
 */
"""

# Models in dependency order so every referenced interface is declared first.
MODELS: list[type[BaseModel]] = [
    schemas.SourceRef,
    schemas.WordBox,
    schemas.KeyClause,
    schemas.Requirement,
    schemas.PassageBytes,
    schemas.Solicitation,
    schemas.CompanyProfile,
    schemas.Notice,
    schemas.FitAssessment,
    schemas.AwardRecord,
    schemas.QuoteLine,
    schemas.Quote,
    schemas.RequirementCheck,
    schemas.QuoteVerdict,
    schemas.QuoteComparison,
    schemas.SourcingDecision,
    schemas.Order,
    schemas.SupplierPO,
    schemas.Shipment,
    schemas.Invoice,
    schemas.Event,
    schemas.OrderDetail,
    schemas.Flag,
    schemas.HealthStatus,
    schemas.ImpactOption,
    schemas.ImpactAnalysis,
    schemas.FigureLineage,
    schemas.LinkedFigure,
    schemas.ContractSection,
    schemas.ContractFile,
    schemas.Ripple,
]


def ts_type(annotation: object) -> str:
    """Map one Pydantic field annotation to a TypeScript type."""
    if annotation is str:
        return "string"
    if annotation is bool:
        return "boolean"
    if annotation is int or annotation is float:
        return "number"
    if annotation is Decimal:
        return "string"
    if annotation is date or annotation is datetime:
        return "string"
    origin = typing.get_origin(annotation)
    args = typing.get_args(annotation)
    if origin is typing.Literal:
        return " | ".join(f'"{value}"' for value in args)
    if origin is dict:
        key, value = args
        return f"Record<{ts_type(key)}, {ts_type(value)}>"
    if origin is list:
        (item,) = args
        return f"{ts_type(item)}[]"
    if origin is typing.Union or origin is types.UnionType:
        return " | ".join("null" if arg is type(None) else ts_type(arg) for arg in args)
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        return annotation.__name__
    raise ValueError(f"generate_types: unsupported annotation {annotation!r}")


def render_model(model: type[BaseModel]) -> str:
    """Render one interface, with required fields non-optional."""
    doc = (model.__doc__ or "").strip().splitlines()
    lines = ["/**", f" * {doc[0]}" if doc else " *", " */", f"export interface {model.__name__} {{"]
    for name, field in model.model_fields.items():
        optional = "" if field.is_required() else "?"
        lines.append(f"  {name}{optional}: {ts_type(field.annotation)};")
    lines.append("}")
    return "\n".join(lines)


def render_file() -> str:
    """Render the full contents of the generated TypeScript file."""
    return HEADER + "\n".join(render_model(model) for model in MODELS) + "\n"


def main() -> int:
    """Write the generated file. Returns process exit code."""
    OUT_PATH.write_text(render_file(), encoding="utf-8")
    print(f"wrote {OUT_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
